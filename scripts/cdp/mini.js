// Browsing shrinks the player into the mini player; autoplay keeps it there; a
// user-started episode opens the full player again.
const { lib, folder } = await setup()
const [a] = episodeNums(lib, folder)
const has = (sel) => !!document.querySelector(sel)
await window.api.setSettings({ autoplayNext: true })
await playEpisode(folder, a)
let s = await loaded()
note('full player', has('.player'))
;[...document.querySelectorAll('.nav-item')].find((x) => x.textContent.startsWith('Library')).click()
await sleep(1500)
s = await window.api.getPlayerState()
note('after clicking Library: mini', has('.mini-player'), '| still playing', s.open && !s.paused)
document.querySelector('.now-streaming').click()
await sleep(800)
note('Now streaming opens the full player', has('.player') && !has('.mini-player'))
document.querySelector('.player-mini-btn').click()
await sleep(800)
await window.api.playerCommand({ type: 'seek', seconds: s.duration - 4 })
await waitFor(async () => { const n = await window.api.getPlayerState(); return n.torrentId !== s.torrentId || n.fileIndex !== s.fileIndex }, 90000, 300)
await sleep(1500)
note('autoplay kept the mini player', has('.mini-player'))
await playEpisode(folder, a)
await sleep(1500)
note('playing from the library opens the full player', has('.player'))
await window.api.playerCommand({ type: 'close' })
await sleep(1500)
return log.join('\n')
