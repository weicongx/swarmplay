// Audio and subtitle picks carry over to the series' other episodes.
const { lib, folder } = await setup()
const [a, b] = episodeNums(lib, folder)
const ready = () => waitFor(async () => { const s = await window.api.getPlayerState(); return s.duration && s.subTracks.length ? s : null }, 120000, 200)
const picked = (s) => `audio ${s.audioTracks.find((x) => x.selected)?.title ?? '-'}, subtitles ${s.subTracks.find((x) => x.selected)?.title ?? 'off'}`
await playEpisode(folder, a)
let s = await ready()
await sleep(1000)
const audio = s.audioTracks.find((x) => !x.selected) ?? s.audioTracks[0]
const sub = s.subTracks[s.subTracks.length - 1]
if (audio) await window.api.playerCommand({ type: 'audio', id: audio.id })
await window.api.playerCommand({ type: 'sub', id: sub.id })
await sleep(800)
const want = picked(await window.api.getPlayerState())
note('picked on episode', a, '->', want)
await playEpisode(folder, b)
await ready()
await sleep(2500)
const got = picked(await window.api.getPlayerState())
note('episode', b, 'started with', got, got === want ? '(same)' : '(DIFFERENT)')
await window.api.playerCommand({ type: 'sub', id: null })
await sleep(500)
await playEpisode(folder, a)
await ready()
await sleep(2500)
note('after turning subtitles off:', picked(await window.api.getPlayerState()))
await window.api.playerCommand({ type: 'close' })
await sleep(2000)
return log.join('\n')
